function normalise(value: string) { return value.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '') }

/** Ranks entries against the query: name prefix, then word prefix, then substring, then extra terms (codes, brands). */
export function searchCatalog<T>(entries: T[], query: string, terms: (entry: T) => { name: string; extra?: string[] }, limit = 12): T[] {
  const q = normalise(query.trim())
  if (!q) return []
  const scored: [number, T][] = []
  for (const entry of entries) {
    const { name, extra = [] } = terms(entry)
    const n = normalise(name)
    let score = -1
    if (n.startsWith(q)) score = 0
    else if (n.split(/[\s/(),-]+/).some(word => word.startsWith(q))) score = 1
    else if (n.includes(q)) score = 2
    else if (extra.some(term => normalise(term).startsWith(q))) score = 3
    else if (extra.some(term => normalise(term).includes(q))) score = 4
    if (score >= 0) scored.push([score, entry])
  }
  return scored.sort((a, b) => a[0] - b[0]).slice(0, limit).map(([, entry]) => entry)
}

export const searchDiagnoses = (query: string) => searchCatalog(DIAGNOSES, query, entry => ({ name: entry.name, extra: [entry.icd10, entry.icd10.replace('.', '')] }))
export const searchAllergens = (query: string) => searchCatalog(ALLERGENS, query, entry => ({ name: entry.name, extra: [entry.category] }))
export const searchMedications = (query: string) => searchCatalog(MEDICATIONS, query, entry => ({ name: entry.name, extra: entry.brands }))

export function findMedication(name?: string) { const n = normalise(name || ''); return n ? MEDICATIONS.find(entry => normalise(entry.name) === n) : undefined }
export function findAllergen(name?: string) { const n = normalise(name || ''); return n ? ALLERGENS.find(entry => normalise(entry.name) === n) : undefined }
